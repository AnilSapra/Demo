import math

no=100
#sqrt

print(f"square root of {no} is {math.sqrt(no)}")
#power
print("3 raised to 4",math.pow(3,4))
#ceil,floor
print("ceil value of 7.1",math.ceil(7.1))
print("floor value of 7.8",math.floor(7.8))

#pi
print("pi value",math.pi)

#factorial
print("factorial of 5",math.factorial(5))

#log
print("log 100 base 10",math.log(100,10))

#sin
print("sin 90 value",math.sin(math.radians(90)))
